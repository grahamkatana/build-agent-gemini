CREATE TABLE IF NOT EXISTS routes (
    id              SERIAL PRIMARY KEY,
    route_code      VARCHAR(20)  NOT NULL UNIQUE,
    name            TEXT         NOT NULL,
    area            TEXT,
    terminus_from   TEXT,
    terminus_to     TEXT,
    cbd_point       TEXT,
    has_start_loop  BOOLEAN      DEFAULT FALSE,
    loop_note       TEXT,
    operator        TEXT         DEFAULT 'Tshwane Bus Services',
    wd_service      BOOLEAN      DEFAULT TRUE,
    sat_service     BOOLEAN      DEFAULT FALSE,
    sat_note        TEXT,
    sun_service     BOOLEAN      DEFAULT FALSE,
    region          TEXT,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS route_variants (
    id              SERIAL PRIMARY KEY,
    route_code      VARCHAR(20)  NOT NULL REFERENCES routes(route_code) ON DELETE CASCADE,
    variant_code    VARCHAR(10)  NOT NULL,
    description     TEXT         NOT NULL,
    direction       VARCHAR(10),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    UNIQUE(route_code, variant_code)
);

CREATE TABLE IF NOT EXISTS stops (
    id              SERIAL PRIMARY KEY,
    route_code      VARCHAR(20)  NOT NULL REFERENCES routes(route_code) ON DELETE CASCADE,
    direction       VARCHAR(10)  NOT NULL,
    sequence_no     INT          NOT NULL,
    name            TEXT         NOT NULL,
    street          TEXT,
    stop_type       VARCHAR(20)  DEFAULT 'stop',
    lon             NUMERIC(10,6),
    lat             NUMERIC(10,6),
    variant_code    VARCHAR(10)  DEFAULT NULL,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS timetable_entries (
    id              SERIAL PRIMARY KEY,
    route_code      VARCHAR(20)  NOT NULL REFERENCES routes(route_code) ON DELETE CASCADE,
    day_type        VARCHAR(20)  NOT NULL,
    direction       VARCHAR(10)  NOT NULL,
    departure_time  TIME         NOT NULL,
    variant_codes   TEXT         DEFAULT NULL,
    notes           TEXT         DEFAULT NULL,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_stops_route_dir
    ON stops(route_code, direction);

CREATE INDEX IF NOT EXISTS idx_tt_lookup
    ON timetable_entries(route_code, day_type, direction, departure_time);

-- Auto-update updated_at on row change
CREATE OR REPLACE FUNCTION tbs_set_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;

DO $$ BEGIN
    CREATE TRIGGER trg_routes_updated_at
        BEFORE UPDATE ON routes
        FOR EACH ROW EXECUTE FUNCTION tbs_set_updated_at();
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

